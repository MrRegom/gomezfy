def resolver_ruta_cookies() -> Optional[str]:
    """
    Retorna la ruta hacia las cookies de YouTube en un directorio con permisos de ESCRITURA (/tmp).
    yt-dlp requiere permisos de escritura en el archivo de cookies para sincronizar sesiones en Vercel.
    """
    tmp_path = os.path.join(tempfile.gettempdir(), "vercel_yt_cookies_writable.txt")

    # 1. Variable de entorno personalizada
    env_cookies = os.environ.get("YOUTUBE_COOKIES")
    if env_cookies and env_cookies.strip():
        try:
            with open(tmp_path, "w", encoding="utf-8") as f:
                f.write(env_cookies.strip() + "\n")
            return tmp_path
        except Exception:
            pass

    # 2. Si existe un archivo físico local, copiarlo a /tmp para evitar Read-only file system
    directorio_actual = os.path.dirname(__file__)
    ruta_local = os.path.join(directorio_actual, "cookies.txt")
    if os.path.exists(ruta_local) and os.path.getsize(ruta_local) > 20:
        try:
            with open(ruta_local, "r", encoding="utf-8") as src, open(tmp_path, "w", encoding="utf-8") as dst:
                dst.write(src.read())
            return tmp_path
        except Exception:
            pass

    # 3. Fallback embebido persistido en /tmp
    try:
        with open(tmp_path, "w", encoding="utf-8") as f:
            f.write(SANITIZED_COOKIES.strip() + "\n")
        return tmp_path
    except Exception:
        return None


class AudioStreamService:
    """Servicio de resolución de URLs de audio nativo (m4a/mp4/aac)."""

    _cache: Dict[str, Dict[str, Any]] = {}
    last_error: str = "None"

    @classmethod
    def obtener_url_audio(cls, video_id: str) -> Optional[Dict[str, Any]]:
        """
        Extrae la URL directa del flujo de audio del video especificado.
        Utiliza el cliente móvil oficial de YouTube autenticado para evadir desafíos JS en Vercel.
        """
        if not video_id or not video_id.strip():
            cls.last_error = "Video ID empty"
            return None

        clean_id = video_id.strip()

        # Caché en memoria para respuesta instantánea (0ms)
        if clean_id in cls._cache:
            return cls._cache[clean_id]

        if not yt_dlp:
            cls.last_error = "yt_dlp no está instalado en Vercel"
            logger.error("yt_dlp no está instalado en el entorno.")
            return None

        ydl_opts = {
            'format': 'bestaudio[ext=m4a]/bestaudio/best',
            'quiet': True,
            'no_warnings': True,
            'extract_flat': False,
            'cachedir': False,
            'socket_timeout': 10,
            'extractor_args': {
                'youtube': {
                    'player_client': ['android'],
                    'player_skip': ['web', 'mweb', 'web_creator', 'ios']
                }
            }
        }

        # En Vercel (IPs de centros de datos de AWS), el cliente Android anónimo NO sufre bloqueos por IP de sesión.
        # Solo adjuntamos cookies si se configuran explícitamente vía variable de entorno.
        env_cookies = os.environ.get("YOUTUBE_COOKIES")
        if env_cookies and env_cookies.strip():
            ruta_cookies = resolver_ruta_cookies()
            if ruta_cookies:
                ydl_opts['cookiefile'] = ruta_cookies

        url = f"https://www.youtube.com/watch?v={clean_id}"

        try:
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                info = ydl.extract_info(url, download=False)
                if not info:
                    cls.last_error = "extract_info devolvió None"
                    return None

                audio_url = info.get('url')
                duration = info.get('duration', 0)
                title = info.get('title', '')
                thumbnail = info.get('thumbnail', '')

                if not audio_url:
                    cls.last_error = "No se encontró audio_url en info"
                    return None

                resultado = {
                    "id": clean_id,
                    "title": title,
                    "audioUrl": audio_url,
                    "duration": duration,
                    "thumbnail": thumbnail,
                    "format": info.get('ext', 'm4a')
                }

                # Limitar tamaño de caché a 100 elementos FIFO
                if len(cls._cache) >= 100:
                    cls._cache.pop(next(iter(cls._cache)))
                cls._cache[clean_id] = resultado

                return resultado
        except Exception as e:
            cls.last_error = f"{type(e).__name__}: {str(e)}"
            logger.exception("Error al resolver stream para el video %s: %s", clean_id, e)
            return None


class handler(BaseHTTPRequestHandler):
    """Manejador Serverless para Vercel Functions."""

    def do_GET(self):
        partes_url = urllib.parse.urlparse(self.path)
        params = urllib.parse.parse_qs(partes_url.query)
        video_id = params.get("id", [""])[0]

        resultado = AudioStreamService.obtener_url_audio(video_id)
        if resultado and resultado.get("audioUrl"):
            respuesta = json.dumps({"status": "success", "stream": resultado}, ensure_ascii=False)
            self.send_response(200)
        else:
            respuesta = json.dumps({
                "status": "error",
                "message": "No se pudo extraer flujo de audio.",
                "debug": AudioStreamService.last_error,
                "yt_dlp_available": yt_dlp is not None
            }, ensure_ascii=False)
            self.send_response(200)

        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "public, max-age=1800")
        self.end_headers()
        self.wfile.write(respuesta.encode("utf-8"))
